// Generates dist/analyzer.js (classic script) and dist/client.js (ESM dev overlay).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { analyzerSource } from '../src/analyzer/bundle.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const banner = '// Generated by scripts/build-client.js — do not edit. Source: src/analyzer, src/client.\n';
mkdirSync(join(root, 'dist'), { recursive: true });
const analyzer = analyzerSource();
writeFileSync(join(root, 'dist/analyzer.js'), banner + analyzer);
const overlay = readFileSync(join(root, 'src/client/overlay.js'), 'utf8');
writeFileSync(join(root, 'dist/client.js'), banner + 'if (typeof window !== "undefined") {\n' + analyzer + '}\n' + overlay);
console.log('dist/analyzer.js and dist/client.js written');
