// Regenerates docs/rules.md from src/rules-meta.js.
import { writeFileSync } from 'node:fs';
import { RULES, IGNORE_HELP } from '../src/rules-meta.js';

const cats = {};
for (const [id, r] of Object.entries(RULES)) (cats[r.category] = cats[r.category] || []).push([id, r]);
let md = '# Rules\n\n<!-- Generated by scripts/gen-docs.js from src/rules-meta.js — do not edit by hand. -->\n\n';
md += 'Every rule can be set to `"error"`, `"warn"` or `"off"` in `renderlint.config.json` → `rules`. Errors fail the run (exit code 1); warnings are reported only.\n\n';
md += '| Rule | Default | What it catches |\n|---|---|---|\n';
for (const [id, r] of Object.entries(RULES)) md += `| [\`${id}\`](#${id}) | ${r.severity} | ${r.summary.replace(/\|/g, '\\|').replace(/</g, '&lt;')} |\n`;
md += '\n';
for (const [cat, list] of Object.entries(cats)) {
  md += `## ${cat[0].toUpperCase() + cat.slice(1)}\n\n`;
  for (const [id, r] of list) md += `### ${id}\n\n**Default:** ${r.severity}\n\n${r.summary}\n\n**How to fix:** ${r.fix}\n\n`;
}
md += `## Intentional exceptions\n\n${IGNORE_HELP}\n\n\`\`\`html\n<div data-renderlint-ignore="emoji" data-renderlint-reason="user-generated chat messages">…</div>\n\`\`\`\n\n\`\`\`css\n.watermark { --renderlint-ignore: contrast; }\n\`\`\`\n\nIn source files (static scan): \`// renderlint-ignore emoji\` on the line or the line above, or \`renderlint-ignore-file\` anywhere in the file.\n`;
writeFileSync(new URL('../docs/rules.md', import.meta.url), md);
console.log('docs/rules.md written');
